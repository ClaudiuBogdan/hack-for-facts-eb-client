#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs'
import { parseArgs } from 'node:util'

const { values } = parseArgs({
  options: {
    source: { type: 'string', default: 'public/geojson/uat-2026-10-28.json' },
    check: { type: 'boolean' },
  },
})
const root = new URL('../', import.meta.url)
const output = new URL('src/features/landing/lib/uat-search-directory.generated.ts', root)
const source = JSON.parse(readFileSync(new URL(values.source, root), 'utf8'))
const mapping = readFileSync(new URL('src/assets/data/uat-cui-map.csv', root), 'utf8')
const [header, ...lines] = mapping.trim().split(/\r?\n/u)
if (header !== 'cui,natcode') throw new Error('Unexpected UAT-to-CUI mapping header')
const cuiBySiruta = new Map()
for (const line of lines) {
  const [cui, siruta, extra] = line.split(',')
  // The same mapping includes county councils keyed by county abbreviation.
  if (extra === undefined && /^[A-Z]{1,2}$/u.test(siruta ?? '')) continue
  if (extra !== undefined || !/^\d{2,10}$/u.test(cui ?? '') || !/^\d+$/u.test(siruta ?? '') || cuiBySiruta.has(siruta)) {
    throw new Error('Invalid or repeated UAT-to-CUI mapping row: ' + line)
  }
  cuiBySiruta.set(siruta, cui)
}

const kinds = new Map([
  ['Comuna', 'commune'],
  ['Oras', 'town'],
  ['Municipiu, altul decat resedinta de judet', 'municipality'],
  ['Municipiu resedinta de judet', 'municipality'],
  ['Sectoarele municipiului Bucuresti', 'sector'],
  ['Municipiu capitala', 'municipality'],
])
const rows = []
const seenCuis = new Set()
function addRow(siruta, cui, name, county, kind) {
  if (!cui || !kind || typeof name !== 'string' || !name.trim() ||
      !/^[A-Z]{1,2}$/u.test(county ?? '') || cuiBySiruta.get(siruta) !== cui || seenCuis.has(cui)) {
    throw new Error('Invalid or repeated public UAT identity for SIRUTA ' + siruta)
  }
  seenCuis.add(cui)
  rows.push([cui, name.trim(), county, kind])
}

for (const feature of source.features) {
  const props = feature.properties
  if (/^(?:judet|consiliu judetean)/iu.test(props.natLevName)) continue
  addRow(props.natcode, props.cui, props.name, props.countyMn, kinds.get(props.natLevName))
}

// The boundary asset represents Bucharest by sector; the capital has its own public profile.
const capitalSiruta = '179132'
const capitalCui = cuiBySiruta.get(capitalSiruta)
if (!seenCuis.has(capitalCui)) addRow(capitalSiruta, capitalCui, 'București', 'B', 'municipality')

rows.sort((a, b) => a[1] < b[1] ? -1 : a[1] > b[1] ? 1 : Number(a[0]) - Number(b[0]))
const text = [
  '// Generated by scripts/generate-uat-search-directory.mjs from ' + values.source + '.',
  "import type { UatDirectoryRow } from './uat-search-ranking'",
  '',
  'export const UAT_SEARCH_DIRECTORY: readonly UatDirectoryRow[] = [',
  ...rows.map(row => '  ' + JSON.stringify(row) + ','),
  ']',
  '',
].join('\n')
if (values.check) {
  if (readFileSync(output, 'utf8') !== text) throw new Error('The UAT search directory needs regenerating')
} else {
  writeFileSync(output, text)
}
console.log(rows.length + ' UAT profiles in the search directory')
