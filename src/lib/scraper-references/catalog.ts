export function getScraperDatasetById(
  datasetId: string,
): ScraperDatasetReference | undefined {
  return scraperDatasetCatalog.find((entry) => entry.id === datasetId)
}

export function listScraperDatasetsByLifecycle(
  lifecycle: ScraperDatasetReference['lifecycle'],
): readonly ScraperDatasetReference[] {
  return scraperDatasetCatalog.filter((entry) => entry.lifecycle === lifecycle)
}

export function listMockFirstDatasets(): readonly ScraperDatasetReference[] {
  return scraperDatasetCatalog.filter(
    (entry) => !entry.apiReady || entry.lifecycle !== 'production',
  )
}
